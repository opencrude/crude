package types

import (
	"bytes"
	"encoding/json"
	"fmt"
)

// WorkspaceAnalysisTrust is a human-owned workspace execution ceiling, not an
// LSP feature toggle, command grant, acquisition approval or sandbox.
type WorkspaceAnalysisTrust string

const (
	AnalysisStaticOnly              WorkspaceAnalysisTrust = "static_only"
	AnalysisProjectExecutionAllowed WorkspaceAnalysisTrust = "project_execution_allowed"
)

// WorkspaceAnalysisSettings is carried by AppSettings for schema/effective
// projections only. Its choices belong exclusively to the workspace overlay;
// application defaults and session preferences cannot supply execution trust.
type WorkspaceAnalysisSettings struct {
	Trust WorkspaceAnalysisTrust `json:"trust"`
}

func DefaultWorkspaceAnalysisSettings() WorkspaceAnalysisSettings {
	return WorkspaceAnalysisSettings{Trust: AnalysisStaticOnly}
}

// NormalizeWorkspaceAnalysis fails closed when reading incomplete or invalid
// stored data. New writes use ValidateAnalysisSettingEdits and reject bad values.
func NormalizeWorkspaceAnalysis(s WorkspaceAnalysisSettings) WorkspaceAnalysisSettings {
	if s.Trust != AnalysisProjectExecutionAllowed {
		s.Trust = AnalysisStaticOnly
	}
	return s
}

func workspaceAnalysisChoice(raw json.RawMessage) WorkspaceAnalysisSettings {
	choice, err := decodeWorkspaceAnalysisChoice(raw)
	if err != nil {
		return DefaultWorkspaceAnalysisSettings()
	}
	return choice
}

// This authority-bearing object has exactly one scalar. Decode its shape rather
// than a map so duplicate/escaped duplicate keys cannot acquire last-key-wins
// authorization before the persistence owner binds the choice.
func decodeWorkspaceAnalysisChoice(raw json.RawMessage) (WorkspaceAnalysisSettings, error) {
	var choice WorkspaceAnalysisSettings
	if len(raw) > 1024 || !json.Valid(raw) {
		return choice, fmt.Errorf("invalid workspace analysis JSON")
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	if token, err := decoder.Token(); err != nil || token != json.Delim('{') {
		return choice, fmt.Errorf("workspace analysis must be an object")
	}
	if token, err := decoder.Token(); err != nil || token != "trust" {
		return choice, fmt.Errorf("workspace analysis requires exactly one trust choice")
	}
	if err := decoder.Decode(&choice.Trust); err != nil {
		return choice, fmt.Errorf("invalid workspace analysis trust: %w", err)
	}
	if decoder.More() {
		return choice, fmt.Errorf("workspace analysis rejects duplicate or unknown fields")
	}
	if token, err := decoder.Token(); err != nil || token != json.Delim('}') {
		return choice, fmt.Errorf("invalid workspace analysis object")
	}
	if choice.Trust != AnalysisStaticOnly && choice.Trust != AnalysisProjectExecutionAllowed {
		return choice, fmt.Errorf("analysis trust must be static_only or project_execution_allowed")
	}
	return choice, nil
}

// ValidateAnalysisSettingEdits validates ownership as well as the exact trust
// enum. Ordinary JSON field/type validation alone does not enforce either.
func ValidateAnalysisSettingEdits(scope SettingsScope, edits []SettingEdit) error {
	for _, edit := range edits {
		if len(edit.Path) != 0 && edit.Path[0] == "analysis_root_identity" {
			return fmt.Errorf("analysis root identity is generated by the workspace preference owner")
		}
		if len(edit.Path) == 0 || edit.Path[0] != "analysis" {
			continue
		}
		if scope != SettingsScopeWorkspace {
			return fmt.Errorf("analysis trust belongs to Workspace settings")
		}
		if len(edit.Path) > 2 || len(edit.Path) == 2 && edit.Path[1] != "trust" {
			return fmt.Errorf("unknown workspace analysis setting")
		}
		if edit.After == nil {
			continue // Reset resolves to Static only, never application inheritance.
		}
		if !json.Valid(edit.After) {
			return fmt.Errorf("invalid workspace analysis JSON")
		}
		var choice WorkspaceAnalysisSettings
		if len(edit.Path) == 1 {
			var err error
			choice, err = decodeWorkspaceAnalysisChoice(edit.After)
			if err != nil {
				return err
			}
		} else if err := json.Unmarshal(edit.After, &choice.Trust); err != nil {
			return fmt.Errorf("invalid workspace analysis trust: %w", err)
		}
		switch choice.Trust {
		case AnalysisStaticOnly, AnalysisProjectExecutionAllowed:
		default:
			return fmt.Errorf("analysis trust must be static_only or project_execution_allowed")
		}
	}
	return nil
}
