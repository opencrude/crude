package rendering

import "strings"

// ExtractLastCodeBlock finds the last ```-fenced code block in the
// given markdown text and returns its language tag (without the
// fences, "" if none) and the code content (without the fences).
// Returns ok=false if no complete fenced code block is present.
//
// The scanner walks lines from the end, looking for a closing fence
// (a line that is exactly "```" or starts with "```" followed by
// nothing else meaningful). It then walks backward to find the
// matching opening fence. The block is well-formed when both fences
// are present and the closing fence appears after the opening one.
//
// This is a deliberately minimal parser: it does not handle nested
// fences, indented code, or HTML pre blocks. For agent message
// markdown (which is typically generated by the model) it is
// sufficient.
func ExtractLastCodeBlock(s string) (lang, code string, ok bool) {
	if s == "" {
		return "", "", false
	}
	lines := strings.Split(s, "\n")

	// Find the closing fence: scan from the end, skip lines that
	// are not exactly "```" (with optional trailing whitespace).
	closeIdx := -1
	for i := len(lines) - 1; i >= 0; i-- {
		line := strings.TrimRight(lines[i], " \t\r")
		if line == "```" {
			closeIdx = i
			break
		}
	}
	if closeIdx <= 0 {
		return "", "", false
	}

	// Walk backward from closeIdx-1 to find the opening fence.
	// An opening fence is either "```" exactly (no language) or
	// "```<lang>" with a typical language tag (letters, digits,
	// _-+#.). A bare "```" line is the most common form.
	openIdx := -1
	openLang := ""
	for i := closeIdx - 1; i >= 0; i-- {
		line := strings.TrimRight(lines[i], " \t\r")
		if !strings.HasPrefix(line, "```") {
			continue
		}
		// Bare "```" with no language tag is a valid opener.
		if line == "```" {
			openIdx = i
			openLang = ""
			break
		}
		// "```<lang>" with a non-empty language tag.
		tag := strings.TrimPrefix(line, "```")
		// Allow only typical language tag characters.
		tagEnd := 0
		for tagEnd < len(tag) {
			c := tag[tagEnd]
			if (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
				(c >= '0' && c <= '9') || c == '_' || c == '-' ||
				c == '+' || c == '#' || c == '.' {
				tagEnd++
				continue
			}
			break
		}
		// Reject if the tag is empty (treated as bare "```")
		// or contains a backtick (mid-line ``` is not a fence).
		if tagEnd == 0 || strings.ContainsRune(tag[:tagEnd], '`') {
			continue
		}
		// Anything after the language tag on the same line must be
		// whitespace (e.g., "```go " for an info string).
		rest := strings.TrimSpace(tag[tagEnd:])
		if rest != "" {
			continue
		}
		openIdx = i
		openLang = tag[:tagEnd]
		break
	}
	if openIdx < 0 {
		return "", "", false
	}

	// Code is everything strictly between the two fences.
	var b strings.Builder
	for i := openIdx + 1; i < closeIdx; i++ {
		if i > openIdx+1 {
			b.WriteByte('\n')
		}
		b.WriteString(lines[i])
	}
	return openLang, b.String(), true
}
