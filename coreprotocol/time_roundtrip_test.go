// Wire timestamps carry an instant, not a Go location. In particular decoding
// zero must not attach the shell's local zone and change its rendered year/time.
func TestWireTimestampRenderedSemantics(t *testing.T) {
	old := time.Local
	time.Local = time.FixedZone("shell-local", -7*60*60)
	t.Cleanup(func() { time.Local = old })
	times := []time.Time{
		{}, time.Unix(0, 0).UTC(), time.Unix(-1, 999999999).UTC(),
		time.Date(1, 1, 1, 0, 0, 0, 1, time.UTC),
		time.Date(9999, 12, 31, 23, 59, 59, 999999999, time.UTC),
		time.Date(2026, 10, 23, 12, 34, 56, 123456789, time.FixedZone("custom", 5*3600+1800)),
		time.Unix(math.MinInt64, 123456789).UTC(),
		time.Unix(math.MaxInt64, 999999999).UTC(),
	}
	for _, instant := range times {
		t.Run(instant.String(), func(t *testing.T) {
			message := types.ConversationMessage{Time: instant, ToolStartTime: instant, LifecycleRetryAt: instant,
				Recovery: &recovery.Status{ID: "incident", State: recovery.Recovering, RetryAt: instant}}
			var decoded types.ConversationMessage
			wireTimeRoundTrip(t, &message, &decoded)
			for _, got := range []time.Time{decoded.Time, decoded.ToolStartTime, decoded.LifecycleRetryAt, decoded.Recovery.RetryAt} {
				assertWireInstant(t, got, instant)
			}
			if decoded.Recovery.CanRetry() != message.Recovery.CanRetry() {
				t.Fatal("wire timestamp changed retry availability")
			}
			// Snapshot hydration uses JSON for supported calendar dates. Compare
			// the display format too: Equal alone hides the original local-zone bug.
			if instant.Year() >= 0 && instant.Year() <= 9999 {
				text, err := json.Marshal(message)
				if err != nil {
					t.Fatal(err)
				}
				var hydrated types.ConversationMessage
				if err := json.Unmarshal(text, &hydrated); err != nil {
					t.Fatal(err)
				}
				if decoded.Time.Format("15:04 2006-01-02") != hydrated.Time.UTC().Format("15:04 2006-01-02") {
					t.Fatalf("wire and hydrated clock paint differ: %v vs %v", decoded.Time, hydrated.Time.UTC())
				}
			}
			snapshot := workspace.AgentSnapshot{LastTokenTime: instant}
			var snapshotOut workspace.AgentSnapshot
			wireTimeRoundTrip(t, &snapshot, &snapshotOut)
			assertWireInstant(t, snapshotOut.LastTokenTime, instant)
			update := coreprotocol.ConversationUpdate{LastTokenTime: instant}
			var updateOut coreprotocol.ConversationUpdate
			wireTimeRoundTrip(t, &update, &updateOut)
			assertWireInstant(t, updateOut.LastTokenTime, instant)
		})
	}
}

func wireTimeRoundTrip(t *testing.T, source coreprotocol.Value, target coreprotocol.Target) {
	t.Helper()
	encoded, err := coreprotocol.Marshal(source)
	if err != nil {
		t.Fatal(err)
	}
	if err := coreprotocol.Decode(encoded, target); err != nil {
		t.Fatal(err)
	}
}

func assertWireInstant(t *testing.T, got, want time.Time) {
	t.Helper()
	if got.Unix() != want.Unix() || got.Nanosecond() != want.Nanosecond() || got.IsZero() != want.IsZero() || got.Location() != time.UTC {
		t.Fatalf("timestamp changed instant/zero/zone: got %v (%d,%d), want UTC %v (%d,%d)", got, got.Unix(), got.Nanosecond(), want.UTC(), want.Unix(), want.Nanosecond())
	}
	if got.Format(time.RFC3339Nano) != want.UTC().Format(time.RFC3339Nano) {
		t.Fatalf("timestamp paint changed: %s vs %s", got.Format(time.RFC3339Nano), want.UTC().Format(time.RFC3339Nano))
	}
}

// These are literal timestamp-32/64/96 spec vectors, not values generated by a
// second call to the same codec. Extension -1 and nsec-before-sec are portable.
func TestWireTimestampInteroperability(t *testing.T) {
	for _, tc := range []struct {
		sec int64
		ns  int64
		hex string
	}{
		{0, 0, "d6ff00000000"},
		{math.MaxUint32, 0, "d6ffffffffff"},
		{0, 1, "d7ff0000000400000000"},
		{1 << 32, 0, "d7ff0000000100000000"},
		{(1 << 34) - 1, 999999999, "d7ffee6b27ffffffffff"},
		{1 << 34, 1, "c70cff000000010000000400000000"},
		{-1, 999999999, "c70cff3b9ac9ffffffffffffffffff"},
		{-62135596800, 0, "c70cff00000000fffffff1886e0900"},
		{math.MinInt64, 1, "c70cff000000018000000000000000"},
		{math.MaxInt64, 999999999, "c70cff3b9ac9ff7fffffffffffffff"},
	} {
		golden, err := hex.DecodeString(tc.hex)
		if err != nil {
			t.Fatal(err)
		}
		instant := time.Unix(tc.sec, tc.ns).UTC()
		if encoded := msgp.AppendTime(nil, instant); !bytes.Equal(encoded, golden) {
			t.Errorf("(%d,%d): timestamp bytes %x, want %x", tc.sec, tc.ns, encoded, golden)
		}
		decoded, rest, err := msgp.ReadTimeBytes(golden)
		if err != nil || len(rest) != 0 {
			t.Fatalf("golden decode: %v (%d trailing bytes)", err, len(rest))
		}
		assertWireInstant(t, decoded, instant)
	}
}

// Exercise every reachable generated type, including embedded snapshots and
// collection elements, with canonical zero and nanosecond-bearing timestamps.
// The preexisting instant-only property test missed a local-zone paint change.
func TestEveryWireTypeTimestampSemantics(t *testing.T) {
	for _, proto := range wireTypes {
		t.Run(reflect.TypeOf(proto).String(), func(t *testing.T) {
			for _, instant := range []time.Time{{}, time.Unix(-1, 123456789).UTC()} {
				value := reflect.New(reflect.TypeOf(proto).Elem())
				fillTimestampFields(value.Elem(), instant, 0)
				decoded := reflect.New(value.Elem().Type())
				wireTimeRoundTrip(t, value.Interface().(coreprotocol.Value), decoded.Interface().(coreprotocol.Target))
				compareTimestampFields(t, decoded.Elem(), value.Elem())
			}
		})
	}
}

func TestWireTimestampRejectsMalformedBeforeFollowingFields(t *testing.T) {
	message := types.ConversationMessage{Role: types.RoleUser, Content: "preserved"}
	encoded, err := coreprotocol.Marshal(&message)
	if err != nil {
		t.Fatal(err)
	}
	_, remaining, err := msgp.ReadArrayHeaderBytes(encoded)
	if err != nil {
		t.Fatal(err)
	}
	// Time is the sixth tuple field; use the real encoded entry point and skip
	// the preceding values rather than hard-coding their byte widths.
	for range 5 {
		remaining, err = msgp.Skip(remaining)
		if err != nil {
			t.Fatal(err)
		}
	}
	prefix := encoded[:len(encoded)-len(remaining)]
	for _, vector := range []string{"d7ffee6b280000000000", "c70cff3b9aca000000000000000000", "c70c05000000000000000000000000"} {
		malformed, err := hex.DecodeString(vector)
		if err != nil {
			t.Fatal(err)
		}
		input := append(append(append([]byte{}, prefix...), malformed...), 0xdd, 255, 255, 255, 255)
		// Satisfy the tuple's minimum remaining-byte guard; the malformed Time
		// must fail before the deliberately invalid, oversized following value.
		input = append(input, make([]byte, 64)...)
		var decoded types.ConversationMessage
		err = coreprotocol.Decode(input, &decoded)
		if err == nil || !strings.Contains(err.Error(), "Time") {
			t.Fatalf("timestamp did not reject before following field: %v", err)
		}
		if vector != "c70c05000000000000000000000000" {
			var invalid msgp.InvalidTimestamp
			if !errors.As(err, &invalid) {
				t.Fatalf("bad nanoseconds not rejected as timestamp: %v", err)
			}
		}
		if decoded.Content != "preserved" || !decoded.Time.IsZero() || decoded.Recovery != nil {
			t.Fatalf("malformed timestamp mutated following state: %+v", decoded)
		}
	}
}

func fillTimestampFields(v reflect.Value, instant time.Time, depth int) {
	if depth > 5 {
		return
	}
	if v.Type() == reflect.TypeFor[time.Time]() {
		v.Set(reflect.ValueOf(instant))
		return
	}
	switch v.Kind() {
	case reflect.Struct:
		for i := range v.NumField() {
			if v.Type().Field(i).IsExported() && v.Type().Field(i).Tag.Get("json") != "-" {
				fillTimestampFields(v.Field(i), instant, depth+1)
			}
		}
	case reflect.Pointer:
		v.Set(reflect.New(v.Type().Elem()))
		fillTimestampFields(v.Elem(), instant, depth+1)
	case reflect.Slice:
		v.Set(reflect.MakeSlice(v.Type(), 1, 1))
		fillTimestampFields(v.Index(0), instant, depth+1)
	case reflect.Array:
		for i := range v.Len() {
			fillTimestampFields(v.Index(i), instant, depth+1)
		}
	}
}

func compareTimestampFields(t *testing.T, got, want reflect.Value) {
	t.Helper()
	if want.Type() == reflect.TypeFor[time.Time]() {
		assertWireInstant(t, got.Interface().(time.Time), want.Interface().(time.Time))
		return
	}
	switch want.Kind() {
	case reflect.Struct:
		for i := range want.NumField() {
			if want.Type().Field(i).IsExported() && want.Type().Field(i).Tag.Get("json") != "-" {
				compareTimestampFields(t, got.Field(i), want.Field(i))
			}
		}
	case reflect.Pointer:
		if !got.IsNil() && !want.IsNil() {
			compareTimestampFields(t, got.Elem(), want.Elem())
		}
	case reflect.Array, reflect.Slice:
		for i := 0; i < got.Len() && i < want.Len(); i++ {
			compareTimestampFields(t, got.Index(i), want.Index(i))
		}
	}
}

func FuzzWireTimestampMessage(f *testing.F) {
	for _, sec := range []int64{math.MinInt64, -62135596800, -1, 0, 1 << 34, math.MaxInt64} {
		f.Add(sec, uint32(999999999))
	}
	f.Fuzz(func(t *testing.T, sec int64, nanos uint32) {
		instant := time.Unix(sec, int64(nanos%1000000000)).UTC()
		message := types.ConversationMessage{Time: instant, LifecycleRetryAt: instant,
			Recovery: &recovery.Status{ID: "incident", State: recovery.Recovering, RetryAt: instant}}
		var decoded types.ConversationMessage
		wireTimeRoundTrip(t, &message, &decoded)
		assertWireInstant(t, decoded.Time, instant)
		assertWireInstant(t, decoded.LifecycleRetryAt, instant)
		assertWireInstant(t, decoded.Recovery.RetryAt, instant)
		if decoded.Recovery.CanRetry() != message.Recovery.CanRetry() {
			t.Fatal("wire timestamp changed retry availability")
		}
	})
}
